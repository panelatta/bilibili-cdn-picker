// Bundle src/ into self-contained Surge scripts and render the module.
//
// Usage:
//   node tools/build.mjs                      write scripts and both local/remote modules
//   node tools/build.mjs --base-url <url/>    also write surge/BilibiliCDNPicker.remote.sgmodule
//                                             with absolute script-path URLs
//   node tools/build.mjs --check              verify surge/ matches src/ (no writes)
//
// Zero dependencies: modules are CommonJS files in src/ with relative
// require() calls only; each one is wrapped in a function and linked through a
// small loader. Surge's JavaScriptCore has no Node module loader.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative, posix, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import moduleValidation from './validate-module.cjs';
const { validateModule } = moduleValidation;

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'surge');
const ENTRIES = {
  'request-router.js': 'src/entries/request-router.js',
  'response-observer.js': 'src/entries/response-observer.js',
  'discovery-runner.js': 'src/entries/discovery-runner.js',
  'control-panel.js': 'src/entries/control-panel.js',
  'network-event.js': 'src/entries/network-event.js',
  'web-control.js': 'src/entries/web-control.js',
};
const MODULE_TEMPLATE = 'src/module/BilibiliCDNPicker.sgmodule';
const MODULE_NAME = 'BilibiliCDNPicker.sgmodule';
const MEDIA_HOST = '(?:(?:upos|cn|ec)-[a-z0-9-]+\\.bilivideo\\.com|upos-[a-z0-9-]+\\.akamaized\\.net)';
const MEDIA_PATTERN = '^(?:http://' + MEDIA_HOST + '(?::80)?|https://' + MEDIA_HOST + '(?::443)?)/upgcxcode/[^?#]+\\.m4s\\?';
const MODULE_ARGS = [
  'enabled={{{ENABLED}}}',
  'mode={{{MODE}}}',
  'region={{{REGION}}}',
  'targetMbps={{{TARGET_MBPS}}}',
  'historyPolicy={{{HISTORY_POLICY}}}',
  'routeRevision={{{ROUTE_REVISION}}}',
  'probePolicy={{{PROBE_POLICY}}}',
  'debug={{{DEBUG}}}',
].join('&');
const REQUIRE_RE = /\brequire\((['"])(\.{1,2}\/[^'"]+)\1\)/g;

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const baseIndex = argv.indexOf('--base-url');
const baseUrl = baseIndex >= 0 ? argv[baseIndex + 1] : JSON.parse(readFileSync(resolve(ROOT, 'tools/remote-module.json'), 'utf8')).baseUrl;
if (!/^https:\/\/[^\s",?#]+\/$/.test(baseUrl || '')) {
  console.error('--base-url must be an https URL ending with "/"');
  process.exit(2);
}

// Pack first-party UI assets as strings. API-only requests never load them.
const assets = Object.fromEntries(Object.entries({ html: 'index.html', js: 'app.browser.js', css: 'app.css', icon: 'icon.svg' })
  .map(([key, file]) => [key, readFileSync(resolve(ROOT, 'src/web', file), 'utf8')]));
new vm.Script(assets.js, { filename: 'app.browser.js' });
const assetPath = resolve(ROOT, 'src/web/assets.json');
const assetText = JSON.stringify(assets) + '\n';
if (check) {
  if (!existsSync(assetPath) || readFileSync(assetPath, 'utf8') !== assetText) {
    console.error('Web assets are out of date; run node tools/build.mjs'); process.exit(1);
  }
} else writeFileSync(assetPath, assetText);

const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
const candidates = JSON.parse(readFileSync(resolve(ROOT, 'data/cdn-candidates.json'), 'utf8'));
const version = 'v' + pkg.version;

function toId(absPath) {
  return relative(ROOT, absPath).split(sep).join(posix.sep);
}

function resolveSpec(fromId, spec) {
  let target = resolve(ROOT, dirname(fromId), spec);
  if (!/\.(js|json)$/.test(target)) target += '.js';
  if (!existsSync(target)) throw new Error(`${fromId}: cannot resolve ${spec}`);
  return toId(target);
}

function collect(entryId) {
  const order = [];
  const defs = new Map();
  (function visit(id) {
    if (defs.has(id)) return;
    const source = readFileSync(resolve(ROOT, id), 'utf8');
    const deps = {};
    defs.set(id, { source, deps });
    if (id.endsWith('.js')) {
      for (const m of source.matchAll(REQUIRE_RE)) {
        deps[m[2]] = resolveSpec(id, m[2]);
        visit(deps[m[2]]);
      }
    }
    order.push(id);
  })(entryId);
  return { order, defs };
}

function bundle(name, entryId) {
  const { order, defs } = collect(entryId);
  const parts = [
    `// Bilibili CDN Picker ${version} · ${name}`,
    '// Generated by tools/build.mjs from src/; edit the sources, not this file.',
    `// Candidate data ${candidates.revision}: derived from ${candidates.source.project} (${candidates.source.license}), personal non-commercial use. See data/NOTICE.md.`,
    '(function () {',
    'var __defs = {};',
  ];
  for (const id of order) {
    const { source, deps } = defs.get(id);
    const body = id.endsWith('.json') ? `module.exports = ${JSON.stringify(JSON.parse(source))};` : source.trimEnd();
    parts.push(`__defs[${JSON.stringify(id)}] = [function (module, exports, require) {\n${body}\n}, ${JSON.stringify(deps)}];`);
  }
  parts.push(
    'var __cache = {};',
    'function __load(id) {',
    '  if (__cache[id]) return __cache[id].exports;',
    '  var def = __defs[id];',
    '  var module = { exports: {} };',
    '  __cache[id] = module;',
    '  def[0].call(module.exports, module, module.exports, function (spec) {',
    '    var target = def[1][spec];',
    "    if (!target) throw new Error('module not bundled: ' + spec);",
    '    return __load(target);',
    '  });',
    '  return module.exports;',
    '}',
    `__load(${JSON.stringify(entryId)});`,
    '})();',
    ''
  );
  const code = parts.join('\n');
  new vm.Script(code, { filename: name }); // syntax check
  return code;
}

function renderModule(base) {
  const text = readFileSync(resolve(ROOT, MODULE_TEMPLATE), 'utf8')
    .replaceAll('@@VERSION@@', version)
    .replaceAll('@@PATTERN@@', MEDIA_PATTERN)
    .replaceAll('@@ARGS@@', MODULE_ARGS)
    .replaceAll('@@BASE@@', base);
  validateModule(text, { remote: !!base });
  return text;
}

const outputs = {};
for (const [name, entry] of Object.entries(ENTRIES)) outputs[name] = bundle(name, entry);
outputs[MODULE_NAME] = renderModule('');
if (baseUrl) {
  const remote = renderModule(baseUrl);
  outputs['BilibiliCDNPicker.remote.sgmodule'] = remote;
  const { defaults } = validateModule(remote, { remote: true });
  defaults.DEBUG = 'true';
  const diagnostic = remote
    .replace(/^#!name=.*$/m, '#!name=Bilibili CDN Picker Diagnostic')
    .replace(/^#!arguments(?:-desc)?=.*\n/gm, '')
    .replace(/\{\{\{(\w+)\}\}\}/g, (_, key) => defaults[key])
    .replace(/argument="([^"]*)"/g, 'argument=$1')
    .replace('[Panel]\n', '[Panel]\nBiliCDN-Loaded = title="BCP v' + pkg.version + ' 已加载", content="静态安装标记。Safari 打开 https://bcp.test 管理测速和查看实时进度。", style=info\n');
  validateModule(diagnostic, { remote: true });
  outputs['BilibiliCDNPicker.diagnostic.sgmodule'] = diagnostic;
}

if (check) {
  const stale = Object.keys(outputs).filter((name) => {
    const path = resolve(OUT_DIR, name);
    return !existsSync(path) || readFileSync(path, 'utf8') !== outputs[name];
  });
  if (stale.length) {
    console.error('surge/ is out of date, run `node tools/build.mjs`: ' + stale.join(', '));
    process.exit(1);
  }
  console.log('surge/ is up to date (' + Object.keys(ENTRIES).length + ' scripts + local/remote modules)');
} else {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, code] of Object.entries(outputs)) {
    writeFileSync(resolve(OUT_DIR, name), code);
    console.log(`surge/${name}  ${(Buffer.byteLength(code) / 1024).toFixed(1)} KiB`);
  }
}
